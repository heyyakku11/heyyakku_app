import 'package:yakku/core/constants/api_constants.dart';
import 'package:yakku/core/router/app_routes.dart';

/// What a shared link opens.
enum AppDeepLinkKind {
  /// `/vote/{shareCode}`: a poll or check someone asked about.
  poll,

  /// `/personality/{shareCode}`: someone's personality card to vote on.
  personality,
}

/// A parsed share link: what it opens and the share code it carries.
class AppDeepLink {
  const AppDeepLink(this.kind, this.shareCode);

  final AppDeepLinkKind kind;
  final String shareCode;

  /// The in-app path for this link.
  String get location => switch (kind) {
    AppDeepLinkKind.poll => AppRoutes.pollVoteLocation(shareCode),
    AppDeepLinkKind.personality => AppRoutes.personalityVoteLocation(shareCode),
  };

  @override
  bool operator ==(Object other) =>
      other is AppDeepLink &&
      other.kind == kind &&
      other.shareCode == shareCode;

  @override
  int get hashCode => Object.hash(kind, shareCode);

  @override
  String toString() => 'AppDeepLink($kind, $shareCode)';
}

/// Parses the canonical shared links `https://<web host>/vote/{shareCode}` and
/// `https://<web host>/personality/{shareCode}`.
///
/// The link carries the card's share code, never its id. The OS only hands
/// the app links for the verified host and the `/vote/` and `/personality/`
/// prefixes (see AndroidManifest.xml / Associated Domains); this is the
/// second, in-app line of validation. Query strings and fragments are never
/// trusted.
abstract final class PollDeepLink {
  /// Share codes are generated by the backend: letters and digits only.
  /// They are case-sensitive, so they are never lower-cased.
  static final RegExp _shareCode = RegExp(r'^[A-Za-z0-9]{6,64}$');

  /// First path segment of a poll link and of a personality card link.
  static const pollSegment = 'vote';
  static const personalitySegment = 'personality';

  /// Query parameter carrying the post-onboarding destination.
  static const returnToParam = 'from';

  static bool isValidShareCode(String? value) =>
      value != null && _shareCode.hasMatch(value);

  /// Returns the share code for a full shared-poll URL, or `null` for any
  /// other host, scheme, path shape or malformed code.
  static String? shareCodeFromUrl(Uri uri, {String? webBaseUrl}) {
    if (!_isOnWebHost(uri, webBaseUrl)) return null;
    return _codeFor(uri.pathSegments, pollSegment);
  }

  /// Same as [shareCodeFromUrl] for an in-app location such as
  /// `/vote/{shareCode}` (go_router drops scheme and host for incoming links).
  static String? shareCodeFromPath(Uri location) =>
      _codeFor(location.pathSegments, pollSegment);

  /// Share code of a full personality card URL, or `null`.
  static String? personalityShareCodeFromUrl(Uri uri, {String? webBaseUrl}) {
    if (!_isOnWebHost(uri, webBaseUrl)) return null;
    return _codeFor(uri.pathSegments, personalitySegment);
  }

  /// Share code of an in-app `/personality/{shareCode}` location, or `null`.
  static String? personalityShareCodeFromPath(Uri location) =>
      _codeFor(location.pathSegments, personalitySegment);

  /// The link an in-app location stands for, whichever kind it is, or `null`.
  static AppDeepLink? fromPath(Uri location) {
    final poll = shareCodeFromPath(location);
    if (poll != null) return AppDeepLink(AppDeepLinkKind.poll, poll);
    final personality = personalityShareCodeFromPath(location);
    if (personality != null) {
      return AppDeepLink(AppDeepLinkKind.personality, personality);
    }
    return null;
  }

  static bool _isOnWebHost(Uri uri, String? webBaseUrl) {
    final base = Uri.tryParse(webBaseUrl ?? ApiConstants.webBaseUrl);
    if (base == null) return false;
    if (uri.scheme.toLowerCase() != 'https') return false;
    return uri.host.toLowerCase() == base.host.toLowerCase();
  }

  static String? _codeFor(List<String> segments, String prefix) {
    final parts = segments.where((s) => s.isNotEmpty).toList(growable: false);
    if (parts.length != 2 || parts.first != prefix) return null;
    final code = parts[1];
    return isValidShareCode(code) ? code : null;
  }

  /// A return-to value is only honoured when it is an in-app shared-poll or
  /// personality-card path.
  static String? safeReturnPath(String? raw) {
    if (raw == null || raw.isEmpty) return null;
    final uri = Uri.tryParse(raw);
    if (uri == null || uri.hasScheme || uri.hasAuthority) return null;
    return fromPath(uri)?.location;
  }
}
